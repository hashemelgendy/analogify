#!/usr/bin/env node
/**
 * Regenerate lib/supabase/types.ts from the linked remote Supabase project.
 *
 * Requires:
 * - supabase CLI auth (npx supabase login) OR SUPABASE_ACCESS_TOKEN
 * - NEXT_PUBLIC_SUPABASE_URL in .env.local (to resolve project ref)
 *
 * Usage: npm run supabase:types
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return;
  const raw = readFileSync(filePath, "utf8");
  for (const line of raw.split(/\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) {
      process.env[key] = value;
    }
  }
}

loadEnvFile(resolve(process.cwd(), ".env.local"));
loadEnvFile(resolve(process.cwd(), ".env"));

const url = process.env.NEXT_PUBLIC_SUPABASE_URL?.trim();
if (!url) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_URL. Set it in .env.local before generating types.",
  );
  process.exit(1);
}

let projectId;
try {
  projectId = new URL(url).host.split(".")[0];
} catch {
  console.error("NEXT_PUBLIC_SUPABASE_URL is not a valid URL.");
  process.exit(1);
}

const result = spawnSync(
  "npx",
  ["supabase", "gen", "types", "typescript", "--project-id", projectId],
  {
    encoding: "utf8",
    maxBuffer: 10 * 1024 * 1024,
  },
);

if (result.status !== 0) {
  console.error(result.stderr || result.stdout || "Type generation failed.");
  process.exit(result.status ?? 1);
}

const generated = result.stdout;
if (!generated.includes("export type Database")) {
  console.error("Unexpected CLI output — Database type missing.");
  process.exit(1);
}

const header = `/**
 * Generated by Supabase CLI from the production project schema.
 *
 * Do not hand-edit table definitions — regenerate after migrations:
 *   npm run supabase:types
 *
 * Generated with:
 *   npx supabase gen types typescript --project-id ${projectId}
 */

`;

const convenience = `

/** Convenience aliases for app services/repositories */
export type ExplanationRow = Tables<"explanations">
export type ExplanationInsert = TablesInsert<"explanations">
export type ExplanationUpdate = TablesUpdate<"explanations">
export type FeedbackRow = Tables<"feedback">
export type FeedbackInsert = TablesInsert<"feedback">
export type FeedbackUpdate = TablesUpdate<"feedback">
export type DifficultyLevelEnum = Enums<"difficulty_level">
export type GenerationModeEnum = Enums<"generation_mode">
`;

const outPath = resolve(process.cwd(), "lib/supabase/types.ts");
writeFileSync(outPath, header + generated.trimEnd() + convenience + "\n", "utf8");
console.log(`Wrote ${outPath} (project-id: ${projectId})`);
